async function carregarCSVDoGithub() {
  try {
    const resp = await fetch("clientes.csv?v=" + Date.now());
    if (!resp.ok) throw new Error("Arquivo clientes.csv não encontrado");
    const texto = await resp.text();
    const lista = parseCSV(texto);
    if (!lista.length) throw new Error("CSV vazio ou inválido");
    salvarClientes(lista);
    mensagemAdmin("Base clientes.csv carregada com " + lista.length + " clientes.", "ok");
    renderizar();
  } catch(e) {
    mensagemAdmin("Erro ao carregar clientes.csv: " + e.message, "erro");
  }
}

function buscarCliente(termo) {
  const bruto = String(termo || "").trim();
  const num = limparNumero(bruto);
  const txt = normalizar(bruto);
  if (!bruto) return null;

  return clientes().find(c => {
    const doc = limparNumero(c.documento);
    const cod = String(c.codigo || "");
    const nome = normalizar(c.nome);
    return (
      cod === num ||
      doc === num ||
      doc.includes(num) ||
      (num.length >= 3 && cod.includes(num)) ||
      (txt.length >= 3 && nome.includes(txt))
    );
  });
}

function dadosRankingCliente(c) {
  const lista = [...clientes()].sort((a,b)=>Number(b.pontos||0)-Number(a.pontos||0));
  const posicao = lista.findIndex(x => String(x.codigo) === String(c.codigo) || limparNumero(x.documento) === limparNumero(c.documento)) + 1;
  const total = lista.length;
  return {posicao, total};
}

