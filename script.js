function baixarModeloCSV() {
  const modelo = "nome,documento,codigo,pontos,compras,categoria\nCLIENTE TESTE,00.000.000/1234-00,1234,1000,1000,PORCELANATO\n";
  const blob = new Blob([modelo], {type:"text/csv;charset=utf-8"});
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = "modelo_clientes_dellapiani.csv";
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

function renderizar() {
  const cs = clientes();
  const rs = resgates();

  const grade = document.getElementById("gradeProdutos");
  if (grade) {
    grade.innerHTML = produtosBlack.map(p => `
      <article class="product-card">
        <img src="${p.img}" alt="${p.nome}" onerror="this.style.display='none'">
        <div class="product-info">
          <h3>${p.nome}</h3>
          <p>${p.desc}</p>
          <div class="tags">${p.tags.map(t => `<span>${t}</span>`).join("")}</div>
        </div>
      </article>
    `).join("");
  }

  const adminRanking = document.getElementById("adminRankingCompleto");
  if (adminRanking) {
    adminRanking.innerHTML = [...cs].sort((a,b)=>Number(b.pontos||0)-Number(a.pontos||0)).map((c,i) => `
      <tr><td>#${i+1}</td><td>${c.nome}</td><td>${c.documento}</td><td>${c.codigo}</td><td>${pontos(c.pontos)}</td><td>${c.pontos >= 100000 ? "Premium" : "Ativo"}</td></tr>
    `).join("");
  }

  const adminClientes = document.getElementById("adminClientes");
  if (adminClientes) {
    adminClientes.innerHTML = cs.map(c => `
      <tr><td>${c.nome}</td><td>${c.documento}</td><td>${c.codigo}</td><td>${pontos(c.pontos)}</td></tr>
    `).join("");
  }

  const adminResgates = document.getElementById("adminResgates");
  if (adminResgates) {
    adminResgates.innerHTML = rs.map(r => `
      <tr><td>${r.cliente}</td><td>${r.codigo}</td><td>${r.premio}</td><td>${pontos(r.pontos)}</td><td>${r.status}</td></tr>
    `).join("");
  }

  const statClientes = document.getElementById("statClientes");
  if (statClientes) statClientes.innerText = cs.length;

  const statPontos = document.getElementById("statPontos");
  if (statPontos) statPontos.innerText = cs.reduce((s,c)=>s+Number(c.pontos||0),0).toLocaleString("pt-BR");

  const statResgates = document.getElementById("statResgates");
  if (statResgates) statResgates.innerText = rs.length;
}

