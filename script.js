function importarArquivoCSV(event) {
  const file = event.target.files[0];
  if (!file) return;
  const reader = new FileReader();
  reader.onload = function(e) {
    const lista = parseCSV(e.target.result);
    if (!lista.length) {
      mensagemAdmin("Arquivo inválido ou vazio.", "erro");
      return;
    }
    salvarClientes(lista);
    mensagemAdmin("Novo arquivo importado com " + lista.length + " clientes.", "ok");
    renderizar();
  };
  reader.readAsText(file, "UTF-8");
}

function importarClientesColados() {
  const texto = document.getElementById("csvImport").value.trim();
  if (!texto) return mensagemAdmin("Cole os dados antes de importar.", "erro");
  const lista = parseCSV(texto);
  if (!lista.length) return mensagemAdmin("Dados inválidos.", "erro");
  salvarClientes(lista);
  mensagemAdmin("Dados colados importados com " + lista.length + " clientes.", "ok");
  renderizar();
}

