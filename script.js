function parseCSV(texto) {
  const linhas = String(texto || "").split(/\r?\n/).map(l => l.trim()).filter(Boolean);
  const lista = [];
  linhas.forEach((linha, idx) => {
    const sep = linha.includes(";") ? ";" : (linha.includes("\t") ? "\t" : ",");
    const p = linha.split(sep).map(x => x.trim());
    if (idx === 0 && normalizar(p[0]).includes("NOME")) return;
    if (p.length < 3) return;

    const nome = p[0] || "";
    const documento = p[1] || "";
    let codigo = p[2] || "";
    let pontosValor = p[3] || "";
    let comprasValor = p[4] || "";
    let categoria = p[5] || "PORCELANATO";

    if (p.length === 4) {
      codigo = codigoDoDocumento(documento);
      pontosValor = p[2];
      comprasValor = p[2];
      categoria = p[3] || "PORCELANATO";
    }

    const pontosNum = Number(limparNumero(pontosValor));
    const comprasNum = Number(limparNumero(comprasValor || pontosValor));

    if (!nome || !documento) return;
    lista.push({
      nome,
      documento,
      codigo: codigo || codigoDoDocumento(documento),
      pontos: pontosNum,
      compras: comprasNum,
      categoria: categoria || "PORCELANATO"
    });
  });
  return lista;
}

